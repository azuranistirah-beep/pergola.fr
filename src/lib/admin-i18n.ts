const dictionaries: Record<AdminLocale, Dict> = { en, id };

export function getDict(locale: AdminLocale): Record<AdminMessageKey, string> {
  return dictionaries[locale] as Record<AdminMessageKey, string>;
}

export function createTranslator(locale: AdminLocale) {
  const dict = dictionaries[locale];
  return (key: AdminMessageKey, vars?: Record<string, string | number>): string => {
    let s = dict[key] ?? key;
    if (vars) {
      for (const [k, v] of Object.entries(vars)) {
        s = s.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
      }
    }
    return s;
  };
}

export async function getT() {
  const locale = await getAdminLocale();
  return { t: createTranslator(locale), locale };
}
