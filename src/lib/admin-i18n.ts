import { cookies } from "next/headers";

export const ADMIN_LOCALES = ["en", "id"] as const;
export type AdminLocale = (typeof ADMIN_LOCALES)[number];
export const DEFAULT_ADMIN_LOCALE: AdminLocale = "en";
const COOKIE_NAME = "pergola_admin_locale";

export async function getAdminLocale(): Promise<AdminLocale> {
  const store = await cookies();
  const v = store.get(COOKIE_NAME)?.value;
  return (ADMIN_LOCALES as readonly string[]).includes(v ?? "")
    ? (v as AdminLocale)
    : DEFAULT_ADMIN_LOCALE;
}

export async function setAdminLocale(locale: AdminLocale) {
  const store = await cookies();
  store.set(COOKIE_NAME, locale, {
    path: "/",
    sameSite: "lax",
    maxAge: 60 * 60 * 24 * 365,
  });
}

