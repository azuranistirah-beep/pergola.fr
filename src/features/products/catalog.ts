export const getProductBySlug = (slug: string) =>
  catalog.find((p) => p.slug === slug);

export const getRelatedProducts = (product: PergolaProduct, limit = 3) =>
  catalog
    .filter((p) => p.slug !== product.slug && p.family === product.family)
    .concat(
      catalog.filter(
        (p) => p.slug !== product.slug && p.material === product.material,
      ),
    )
    .filter((p, i, a) => a.findIndex((x) => x.slug === p.slug) === i)
    .slice(0, limit);
